const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const out=__dirname;
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ORCH_CHROMIUM || '/Users/zhangshaohua/Library/Caches/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-mac-arm64/chrome-headless-shell'});
 const results=[];
 try{for(const width of [1280,390,320])for(const dark of [false,true]){
  const p=await browser.newPage({viewport:{width,height:width===1280?900:844}}), errors=[];
  p.setDefaultTimeout(12000);
  p.on('pageerror',e=>errors.push(e.message));
  await p.goto('http://127.0.0.1:4337/dev-docs/session-orchestration/preview.html');
  const summary=p.locator('[data-execution-status] button[aria-expanded]').first();
  await summary.waitFor();
  if(dark){await p.getByRole('button',{name:'切换明暗主题',exact:true}).click();await p.waitForTimeout(250);}
  await summary.click();
  const panel=p.getByRole('region',{name:'任务编排',exact:true});
  await panel.getByText('修复接口权限并完成回归验收',{exact:true}).waitFor();
  assert.match(await panel.innerText(),/执行中/);
  const prefix=`independent-${width}-${dark?'dark':'light'}`;
  await p.screenshot({path:path.join(out,`${prefix}-running.png`),fullPage:true});
  await p.getByRole('button',{name:'回传结果',exact:true}).click();
  await panel.getByText('待验收',{exact:true}).first().waitFor();
  await p.getByRole('button',{name:'验收返工',exact:true}).click();
  await panel.getByText('待返工',{exact:true}).waitFor();
  await p.getByRole('button',{name:'重试',exact:true}).click();
  await p.getByRole('button',{name:'旧结果晚到',exact:true}).click();
  await panel.getByText('执行中',{exact:true}).first().waitFor();
  await p.getByRole('button',{name:'回传结果',exact:true}).click();
  await panel.getByText('待验收',{exact:true}).first().waitFor();
  await p.getByRole('button',{name:'主 Agent 验收通过',exact:true}).click();
  await panel.locator('summary').filter({hasText:/已完成/}).click();
  await panel.getByText('已完成',{exact:true}).first().waitFor();
  await p.screenshot({path:path.join(out,`${prefix}-accepted.png`),fullPage:true});
  await p.getByRole('button',{name:'断线',exact:true}).click();
  await panel.getByText(/同步暂不可用/).waitFor({timeout:6000});
  assert.match(await panel.innerText(),/已完成/);
  await p.screenshot({path:path.join(out,`${prefix}-offline.png`),fullPage:true});
  await p.getByRole('button',{name:'重新连接',exact:true}).click();
  await panel.getByText(/同步暂不可用/).waitFor({state:'detached',timeout:6000});
  await p.getByRole('button',{name:'切换会话',exact:true}).click();
  await p.getByText('修复接口权限并完成回归验收',{exact:true}).waitFor({state:'detached'});
  await p.getByRole('button',{name:'切换会话',exact:true}).click();
  if(await summary.getAttribute('aria-expanded')!=='true') await summary.click();
  await panel.locator('summary').filter({hasText:/已完成/}).click();
  await panel.getByText('已完成',{exact:true}).first().waitFor();
  await p.keyboard.press('Escape');
  assert.equal(await summary.getAttribute('aria-expanded'),'false');
  assert.equal(await summary.evaluate(e=>e===document.activeElement),true);
  await summary.click();
  await panel.locator('summary').filter({hasText:/已完成/}).click();
  await panel.locator('summary').filter({hasText:/执行记录/}).click();
  await panel.getByRole('button').filter({hasText:/reviewer/}).first().click();
  await p.getByRole('dialog').waitFor();
  await p.screenshot({path:path.join(out,`${prefix}-inspector.png`),fullPage:true});
  await p.keyboard.press('Escape');
  await p.getByRole('dialog').waitFor({state:'detached'});
  const overflow=await p.evaluate(()=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(overflow.scroll<=overflow.viewport,JSON.stringify(overflow));
  assert.deepEqual(errors,[]);
  results.push({width,dark,passed:true,overflow});
  await p.close();
 }}finally{await browser.close();fs.writeFileSync(path.join(out,'independent-results.json'),JSON.stringify(results,null,2));}
 console.log(JSON.stringify(results,null,2));
})().catch(e=>{console.error(e);process.exitCode=1});
